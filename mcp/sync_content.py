"""Copy the site's content into the MCP Worker as a Python module.

The Worker can't read the repo at runtime, so this writes src/site_content.py from the site's
Markdown (../src/content). Run it before `pywrangler dev` or `deploy`, as `npm run mcp:dev` and
`npm run mcp:deploy` do; the generated file isn't committed.
"""

import json
import re
from pathlib import Path

HERE = Path(__file__).parent
SITE_CONTENT = HERE.parent / "src" / "content"
OUT = HERE / "src" / "site_content.py"
SITE_URL = "https://bradleygrantham.com"


def parse_frontmatter(raw: str) -> tuple[dict[str, str], str]:
    """Split a post into its frontmatter (simple `key: "value"` lines) and body."""
    match = re.match(r"---\n(.*?)\n---\n", raw, re.S)
    if not match:
        raise ValueError("post has no frontmatter")

    meta = {}
    for line in match.group(1).splitlines():
        key, _, value = line.partition(":")
        value = value.strip()
        meta[key.strip()] = json.loads(value) if value.startswith('"') else value
    return meta, raw[match.end() :]


def describe_jsx(block: str) -> str:
    """A text placeholder for an embedded component (chart, video) the model can't see."""
    title = re.search(r'\btitle="([^"]*)"', block)
    kind = "Video" if "<iframe" in block else "Chart"
    label = f"{kind}: {title.group(1)}" if title else kind
    return f"[{label} (see the post on the website)]"


def mdx_to_markdown(body: str) -> str:
    """Turn an MDX post body into plain Markdown for a model to read.

    Top-level JSX blocks (charts, embedded videos) become short placeholders, and site-relative
    links and images become absolute URLs. Code fences are left untouched.
    """
    lines = body.splitlines()
    out = []
    in_fence = False
    i = 0
    while i < len(lines):
        line = lines[i]
        if line.lstrip().startswith("```"):
            in_fence = not in_fence
        tag = None if in_fence else re.match(r"<([A-Za-z][\w.]*)", line)
        if tag:
            # Consume the block up to its matching closing tag, or a self-closing "/>" at the same
            # indentation as the opening tag (an indented one belongs to a nested element).
            closing = f"</{tag.group(1)}>"
            indent = len(line) - len(line.lstrip())
            block = [line]
            while not (
                closing in block[-1]
                or (block[-1].strip().endswith("/>") and len(block[-1]) - len(block[-1].lstrip()) == indent)
            ):
                i += 1
                block.append(lines[i])
            out.append(describe_jsx("\n".join(block)))
        else:
            out.append(line)
        i += 1

    text = "\n".join(out)
    text = re.sub(r"\]\(/", f"]({SITE_URL}/", text)
    return text.strip()


def load_posts() -> list[dict[str, str]]:
    posts = []
    for path in sorted((SITE_CONTENT / "posts").glob("*.mdx")):
        meta, body = parse_frontmatter(path.read_text(encoding="utf-8"))
        posts.append(
            {
                "slug": path.stem,
                "title": meta["title"],
                "date": meta["date"],
                "summary": meta["summary"],
                "body": mdx_to_markdown(body),
            }
        )
    return sorted(posts, key=lambda post: post["date"], reverse=True)


def main():
    about = (SITE_CONTENT / "about.md").read_text(encoding="utf-8").strip()
    cv_path = SITE_CONTENT / "cv.md"
    cv = cv_path.read_text(encoding="utf-8").strip() if cv_path.exists() else None

    OUT.write_text(
        '"""Generated by sync_content.py from the site\'s src/content. Don\'t edit."""\n\n'
        f"ABOUT = {about!r}\n\n"
        f"CV = {cv!r}\n\n"
        f"POSTS = {load_posts()!r}\n",
        encoding="utf-8",
    )
    print(f"Wrote {OUT.relative_to(HERE)}")


if __name__ == "__main__":
    main()
